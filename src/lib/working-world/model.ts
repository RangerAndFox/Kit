import { WORLD_AGENTS, WORLD_REFRESH_MS } from './catalog'
import type { WorldAgent, WorldAnswer, WorldSnapshot, WorldSource, WorldState, WorldTask } from './types'

const ACTIVE = new Set(['running', 'processing', 'uploading', 'applying', 'claimed', 'logging', 'in_progress'])
const WAITING = new Set(['awaiting', 'collision', 'awaiting_review', 'pending', 'queued', 'retry', 'retryable', 'approved', 'parsed', 'needs_clarification', 'clarification_needed', 'unconfirmed', 'expired', 'sent', 'nudged'])
const BLOCKED = new Set(['failed', 'error', 'needs_review', 'review', 'dead_letter', 'partial'])
const IDLE = new Set(['complete', 'completed', 'logged', 'cancelled', 'canceled', 'skipped', 'superseded', 'synced', 'success'])

export function recordedState(status: string, at: string | null, now: number): WorldState {
  if (BLOCKED.has(status)) return 'blocked'
  if (WAITING.has(status)) return 'waiting'
  if (ACTIVE.has(status)) {
    const stamp = at ? Date.parse(at) : NaN
    return !Number.isFinite(stamp) || now - stamp > 30 * 60_000 ? 'unknown' : 'working'
  }
  return IDLE.has(status) ? 'idle' : 'unknown'
}

export function safeDetail(input: unknown): string {
  return String(input || '').replace(/https?:\/\/[^\s<>]+/gi, '[provider link]')
    .replace(/Bearer\s+[^\s,;]+/gi, 'Bearer [redacted]')
    .replace(/((?:token|secret|api[_-]?key|authorization)["\s:=]+)[^\s,;}]+/gi, '$1[redacted]')
    .replace(/[\u0000-\u001f\u007f]/g, ' ').slice(0, 500)
}

// Workspace identity, not an inferred name or source-supplied hostname, binds
// the permalink domain. Unknown teams retain the internal project fallback.
const SLACK_WORKSPACE_HOSTS: Record<string, string> = { T4ATY2XAL: 'rangerandfox.slack.com' }
export function slackReceipt(channel: unknown, timestamp: unknown, teamId?: unknown): string | null {
  const host = typeof teamId === 'string' ? SLACK_WORKSPACE_HOSTS[teamId] : null
  if (!host) return null
  if (typeof channel !== 'string' || !/^[CDG][A-Z0-9]{5,}$/.test(channel) ||
    typeof timestamp !== 'string' || !/^\d{10,}\.\d{6}$/.test(timestamp)) return null
  return `https://${host}/archives/${channel}/p${timestamp.replace('.', '')}`
}

/** Only URLs generated by trusted adapters may be exposed as navigation. */
export function safeWorldHref(href: string | null | undefined): string | null {
  if (!href) return null
  if (/^\/control-center(?:\/projects\/[a-f0-9-]{36})?$/.test(href) || href === '/status') return href
  try {
    const u = new URL(href)
    if (u.protocol !== 'https:' || u.username || u.password || u.port || u.search || u.hash) return null
    if (Object.values(SLACK_WORKSPACE_HOSTS).includes(u.hostname) && /^\/archives\/[CDG][A-Z0-9]{5,}\/p\d+$/.test(u.pathname)) return u.href
  } catch { /* Invalid provider metadata is not a navigable session. */ }
  return null
}

const priority: Record<WorldState, number> = { blocked: 6, working: 5, waiting: 4, unknown: 3, idle: 1, unconnected: 0 }
export function buildWorldSnapshot(args: {
  workspaceName: string; observedAt: string; tasks: WorldTask[]; sources: WorldSource[]
  health?: Array<{ agentId: string; state: WorldState; detail: string; at: string | null }>
}): WorldSnapshot {
  const agents: WorldAgent[] = WORLD_AGENTS.map(definition => {
    const tasks = args.tasks.filter(t => t.agentId === definition.id).map(t => ({ ...t, href: safeWorldHref(t.href), detail: safeDetail(t.detail) }))
      .sort((a, b) => priority[b.state] - priority[a.state] || (b.at || '').localeCompare(a.at || ''))
    const feeds = args.sources.filter(s => definition.sources.includes(s.id))
    const incomplete = feeds.length !== definition.sources.length || feeds.some(s => !s.available)
    const active = tasks.filter(t => t.state !== 'idle')
    const checks = (args.health || []).filter(h => h.agentId === definition.id)
    const state: WorldState = definition.kind === 'external' ? 'unconnected' : incomplete ? 'unknown'
      : [...active.map(t => t.state), ...checks.map(h => h.state), 'idle' as WorldState].sort((a, b) => priority[b] - priority[a])[0]
    const detail = state === 'unconnected' ? definition.description
      : incomplete ? 'At least one required feed is unavailable. Last-known work is not a current health claim.'
      : checks.find(h => h.state === state)?.detail || active.find(t => t.state === state)?.detail ||
        (feeds.some(s => s.truncated) ? 'Bounded view: more open records exist. Open Control Center for the full queue.' : 'No active work in the connected records. This does not imply a process is running.')
    return { ...definition, state, observedAt: incomplete || definition.kind === 'external' ? null : args.observedAt, detail: safeDetail(detail), tasks, sessionHref: null }
  })
  const events = args.tasks.filter(t => t.at).sort((a, b) => (b.at || '').localeCompare(a.at || '')).slice(0, 20)
    .map(t => ({ ...t, href: safeWorldHref(t.href), detail: safeDetail(t.detail) }))
  return { version: 1, workspaceName: args.workspaceName, observedAt: args.observedAt, refreshMs: WORLD_REFRESH_MS, readOnly: true, agents, events, sources: args.sources }
}

export function explainWorld(snapshot: WorldSnapshot, question: string, agentId?: string): WorldAnswer {
  const q = question.toLowerCase()
  const selected = snapshot.agents.find(a => a.id === agentId) || snapshot.agents.find(a => a.id !== 'kit' && q.includes(a.id))
  let agents = selected ? [selected] : snapshot.agents
  if (!selected) {
    if (/approv|confirm|waiting|queued/.test(q)) agents = agents.filter(a => a.state === 'waiting' || a.tasks.some(t => t.state === 'waiting'))
    else if (/attention|next/.test(q)) agents = agents.filter(a => ['blocked', 'unknown', 'waiting'].includes(a.state))
    else if (/block|fail|error|wrong|fix|problem/.test(q)) agents = agents.filter(a => ['blocked', 'unknown'].includes(a.state))
  }
  const evidence: WorldAnswer['evidence'] = []
  const findings: string[] = []
  for (const agent of agents.slice(0, 3)) {
    if (agent.state === 'unconnected') { findings.push(`${agent.name}: no authorized activity feed or session link is connected. Connect that system before treating it as monitored.`); continue }
    const tasks = agent.tasks.filter(t => t.state !== 'idle').slice(0, 1)
    findings.push(`${agent.name}: ${agent.detail.slice(0, 220)}`)
    for (const task of tasks) {
      let next = task.state === 'waiting' ? 'Open the source request; a queue or human approval is not a service outage.'
        : task.state === 'unknown' ? 'Check the source job and last heartbeat before retrying; current progress is not confirmed.'
          : task.state === 'blocked' ? 'Inspect the source error and preserve existing receipts before choosing a retry.' : 'The recorded job is in progress.'
      if (/source.*(missing|not.found)|path\/not_found/i.test(task.detail)) next = 'Check whether the delivery already exists in Frame before retrying a missing Dropbox source.'
      if (/collision|same.name|duplicate/i.test(task.detail + task.recordedStatus)) next = 'The original approver should choose Replace, Keep both, or Skip. Do not create an automatic duplicate.'
      if (task.recordedStatus === 'approved') next = 'Approval is already recorded. Check the worker queue; do not ask for the same approval again.'
      if (task.recordedStatus === 'expired') next = 'The old confirmation card expired. Reconcile its Harvest receipts before making a new time entry.'
      findings.push(`${task.title}: ${next}`)
      if (task.href) evidence.push({ label: `Open ${task.title}`, href: task.href })
    }
    if (!tasks.length && ['unknown', 'blocked'].includes(agent.state)) evidence.push({ label: `Inspect ${agent.name} health`, href: '/status' })
  }
  return { text: (findings.length ? findings.join('\n\n') : 'No matching active issue is present in the available records. Unconnected systems and unavailable feeds are not confirmed healthy.') + '\n\nRead-only diagnostics: no jobs were retried and nothing was changed.', evidence: evidence.slice(0, 6), observedAt: snapshot.observedAt }
}
